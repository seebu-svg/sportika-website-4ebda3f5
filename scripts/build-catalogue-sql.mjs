#!/usr/bin/env node
/*
 * Render supabase/web-migrations/data/prototype-catalogue.json into one
 * idempotent migration: supabase/web-migrations/web_0007_catalogue_seed.sql
 *
 *   node scripts/build-catalogue-sql.mjs
 *
 * Only website-owned tables are touched (public.web_*). The mobile app's
 * tournaments / matches / profiles are never written to.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const dataFile = path.join(root, "supabase", "web-migrations", "data", "prototype-catalogue.json");
const outFile = path.join(root, "supabase", "web-migrations", "web_0007_catalogue_seed.sql");

const data = JSON.parse(fs.readFileSync(dataFile, "utf8"));

/** SQL string literal. Single quotes doubled; nothing else is interpolated. */
const q = (v) => {
  if (v === null || v === undefined || v === "") return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  return `'${String(v).replace(/'/g, "''")}'`;
};

/** Always-quoted literal, for not-null text columns. */
const t = (v) => `'${String(v ?? "").replace(/'/g, "''")}'`;
const jsonb = (v) => `'${JSON.stringify(v ?? []).replace(/'/g, "''")}'::jsonb`;

/** Render `insert into <table> (cols) values (...), (...);` in batches. */
function insert(table, cols, rows, batch = 60) {
  if (!rows.length) return "";
  const out = [];
  for (let i = 0; i < rows.length; i += batch) {
    const slice = rows.slice(i, i + batch);
    out.push(
      `insert into public.${table} (${cols.join(", ")}) values\n` +
        slice.map((r) => `  (${r.join(", ")})`).join(",\n") +
        ";\n",
    );
  }
  return out.join("");
}

/* --------------------------------------------------------------- rankings */

// unique (sport, city, name): drop generator collisions, then re-rank.
const seen = new Set();
const rankings = [];
for (const r of data.rankings) {
  const key = `${r.sport}|${r.city}|${r.name}`;
  if (seen.has(key)) continue;
  seen.add(key);
  rankings.push(r);
}
const ranked = Object.values(
  rankings.reduce((acc, r) => {
    (acc[`${r.sport}|${r.city}`] ??= []).push(r);
    return acc;
  }, {}),
).flatMap((rows) => rows.sort((a, b) => b.points - a.points).map((r, i) => ({ ...r, rank: i + 1 })));

/* ------------------------------------------------------------------ build */

const parts = [];
parts.push(`-- ============================================================================
-- Sportika website — prototype catalogue seed (generated).
--
-- Generated by scripts/build-catalogue-sql.mjs from
--   scripts/extract-prototypes.mjs -> data/prototype-catalogue.json
-- Do not edit by hand: re-run the two scripts and re-apply this file.
--
-- Writes ONLY website-owned public.web_* tables. The mobile app's
-- tournaments / matches / profiles are never touched, and the mobile RLS
-- policies are unchanged. Idempotent: the website catalogue is replaced on
-- every run, so counts always match the prototypes.
-- ============================================================================

begin;

-- Clear only the content this seed owns.
delete from public.web_catalogue_matches;
delete from public.web_catalogue_players;
delete from public.web_catalogue_events;
delete from public.web_trials;
delete from public.web_posts;
delete from public.web_champions;
delete from public.web_podcast_episodes;
delete from public.web_gallery_items;
delete from public.web_coaches;
delete from public.web_ambassadors;
delete from public.web_societies;
delete from public.web_team_members;
delete from public.web_sponsors;
delete from public.web_clubs;
delete from public.web_venues;
delete from public.web_rankings;

/* ------------------------------------------------------- tournaments (14) */

`);

parts.push(
  insert(
    "web_catalogue_events",
    [
      "slug", "name", "sport", "city", "status", "status_label", "prize", "date_label",
      "venue", "teams_label", "entry_fee", "capacity", "start_date", "end_date",
      "cover_image", "description", "organizer_id", "featured", "sort_order",
    ],
    data.events.map((e) => [
      t(e.slug), t(e.name), t(e.sport), t(e.city), t(e.status), t(e.status_label),
      q(e.prize), t(e.date_label), q(e.venue), q(e.teams_label), q(e.entry_fee),
      q(e.capacity), q(e.start_date), q(e.end_date), q(e.cover_image), t(e.description),
      "null", e.featured ? "true" : "false", String(e.sort_order ?? 0),
    ]),
  ),
);

parts.push(`\n/* ------------------------------------------------------------ players (${data.players.length}) */\n\n`);
parts.push(
  insert(
    "web_catalogue_players",
    ["slug", "name", "sport", "city", "position", "rating", "achievement", "featured", "bio", "stats", "avatar_url", "verified", "level", "age", "sort_order"],
    data.players.map((p) => [
      t(p.slug), t(p.name), t(p.sport), t(p.city), q(p.position), q(p.rating), q(p.achievement),
      p.featured ? "true" : "false", q(p.bio), jsonb(p.stats), "null",
      p.verified ? "true" : "false", q(p.level), q(p.age), String(p.sort_order ?? 0),
    ]),
  ),
);

parts.push(`\n/* ---------------------------------------------------------- fixtures (${data.matches.length}) */\n\n`);
parts.push(
  insert(
    "web_catalogue_matches",
    ["id", "tournament_slug", "team_a", "team_b", "score_a", "score_b", "status", "clock", "court", "scheduled_at", "stage", "sort_order"],
    data.matches.map((m) => [
      t(m.id), t(m.tournament_slug), t(m.team_a), t(m.team_b), String(m.score_a ?? 0), String(m.score_b ?? 0),
      t(m.status), q(m.clock), q(m.court), q(m.scheduled_at), t(m.stage), String(m.sort_order ?? 0),
    ]),
  ),
);

parts.push(`\n/* ---------------------------------------------- trials & scholarships (${data.trials.length}) */\n\n`);
parts.push(
  insert(
    "web_trials",
    ["id", "kind", "organizer", "title", "sport", "city", "deadline", "eligibility", "verified", "sort_order"],
    data.trials.map((x) => [
      t(x.id), t(x.kind), t(x.organizer), t(x.title), t(x.sport), t(x.city), q(x.deadline),
      q(x.eligibility), x.verified ? "true" : "false", String(x.sort_order ?? 0),
    ]),
  ),
);

parts.push(`\n/* ------------------------------------------------------- news + blogs (${data.posts.length}) */\n\n`);
parts.push(
  insert(
    "web_posts",
    ["slug", "type", "category", "title", "excerpt", "cover_image", "body", "status", "published_label", "published_at"],
    data.posts.map((p) => [
      t(p.slug), t(p.type), t(p.category), t(p.title), q(p.excerpt), "null", q(p.body),
      "'published'", t(p.published_label), q(p.published_at),
    ]),
  ),
);

parts.push(`\n/* ------------------------------------------------------------ champions (${data.champions.length}) */\n\n`);
parts.push(
  insert(
    "web_champions",
    ["sport", "tournament", "year", "winner", "runner_up", "score", "image"],
    data.champions.map((c) => [t(c.sport), t(c.tournament), t(c.year), t(c.winner), q(c.runner_up), q(c.score), "null"]),
  ),
);

parts.push(`\n/* --------------------------------------------------------------- podcast (${data.episodes.length}) */\n\n`);
parts.push(
  insert(
    "web_podcast_episodes",
    ["episode_no", "title", "description", "duration", "cover_image", "youtube_id"],
    data.episodes.map((e) => [String(e.episode_no), t(e.title), q(e.description), q(e.duration), "null", q(e.youtube_id)]),
  ),
);

parts.push(`\n/* --------------------------------------------------------------- gallery (${data.gallery.length} albums) */\n\n`);
parts.push(
  insert(
    "web_gallery_items",
    ["album", "album_slug", "caption", "image"],
    data.gallery.map((g) => [t(g.album), t(g.album_slug), q(g.caption), t(g.image ?? "")]),
  ),
);

const directory = [
  ["web_coaches", data.coaches],
  ["web_ambassadors", data.ambassadors],
  ["web_societies", data.societies],
  ["web_team_members", data.team],
];
for (const [table, rows] of directory) {
  parts.push(`\n/* ---------------------------------------------------- ${table} (${rows.length}) */\n\n`);
  parts.push(
    insert(table, ["name", "title", "sport", "city", "image", "blurb"], rows.map((r) => [t(r.name), t(r.title), q(r.sport), q(r.city), "null", q(r.blurb)])),
  );
}

parts.push(`\n/* --------------------------------------------------------------- sponsors (${data.sponsors.length}) */\n\n`);
parts.push(insert("web_sponsors", ["name", "position", "logo_url"], data.sponsors.map((s) => [t(s.name), String(s.position), "null"])));

parts.push(`\n/* ----------------------------------------------------------- clubs (${data.clubs.length}) */\n\n`);
parts.push(
  insert(
    "web_clubs",
    ["slug", "type", "name", "sports", "area", "city", "description", "verified", "featured", "founded", "players", "training", "coaches", "highlights", "image"],
    data.clubs.map((c) => [
      t(c.slug), t(c.type), t(c.name), jsonb(c.sports), t(c.area), t(c.city), t(c.description),
      c.verified ? "true" : "false", c.featured ? "true" : "false", q(c.founded), q(c.players),
      q(c.training), jsonb(c.coaches), q(c.highlights), "null",
    ]),
  ),
);

parts.push(`\n/* ----------------------------------------------------------- venues (${data.venues.length}) */\n\n`);
parts.push(
  insert(
    "web_venues",
    ["slug", "type", "name", "sports", "area", "city", "description", "verified", "featured", "courts", "price", "hours", "amenities", "image"],
    data.venues.map((v) => [
      t(v.slug), t(v.type), t(v.name), jsonb(v.sports), t(v.area), t(v.city), t(v.description),
      v.verified ? "true" : "false", v.featured ? "true" : "false", q(v.courts), q(v.price),
      q(v.hours), q(v.amenities), "null",
    ]),
  ),
);

parts.push(`\n/* --------------------------------------------------------- rankings (${ranked.length}) */\n\n`);
parts.push(
  insert(
    "web_rankings",
    ["sport", "city", "rank", "name", "club", "matches", "points", "delta"],
    ranked.map((r) => [t(r.sport), t(r.city), String(r.rank), t(r.name), t(r.club), String(r.matches), String(r.points), String(r.delta)]),
  ),
);

parts.push(`
commit;
`);

fs.writeFileSync(outFile, parts.join(""));

const kb = (fs.statSync(outFile).size / 1024).toFixed(1);
console.log(`\nweb_0007_catalogue_seed.sql written (${kb} kB)`);
console.log(`  events ${data.events.length} · players ${data.players.length} · fixtures ${data.matches.length} · trials ${data.trials.length}`);
console.log(`  posts ${data.posts.length} · champions ${data.champions.length} · podcast ${data.episodes.length} · gallery ${data.gallery.length}`);
console.log(`  coaches ${data.coaches.length} · ambassadors ${data.ambassadors.length} · societies ${data.societies.length} · team ${data.team.length}`);
console.log(`  sponsors ${data.sponsors.length} · clubs ${data.clubs.length} · venues ${data.venues.length} · rankings ${ranked.length}\n`);
